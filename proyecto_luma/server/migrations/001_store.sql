CREATE TABLE users (
  id text PRIMARY KEY,
  name varchar(80) NOT NULL,
  email text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE admins (user_id text PRIMARY KEY REFERENCES users);

CREATE TABLE categories (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(60) NOT NULL UNIQUE,
  slug text NOT NULL UNIQUE,
  active boolean NOT NULL DEFAULT true
);
CREATE TABLE products (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id integer NOT NULL REFERENCES categories,
  sku varchar(40) NOT NULL UNIQUE,
  name varchar(100) NOT NULL,
  description text NOT NULL,
  material text NOT NULL,
  care text NOT NULL,
  price integer NOT NULL CHECK (price BETWEEN 0 AND 1000000),
  image text NOT NULL,
  badge varchar(40) NOT NULL,
  featured boolean NOT NULL,
  active boolean NOT NULL DEFAULT true
);
CREATE INDEX products_category_idx ON products(category_id);
CREATE TABLE product_variants (
  id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  product_id integer NOT NULL REFERENCES products,
  size varchar(32) NOT NULL,
  stock integer NOT NULL CHECK (stock >= 0),
  active boolean NOT NULL DEFAULT true,
  UNIQUE(product_id, size)
);
CREATE TABLE favorites (
  user_id text NOT NULL REFERENCES users,
  product_id integer NOT NULL REFERENCES products,
  PRIMARY KEY(user_id, product_id)
);
CREATE TABLE coupons (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code varchar(20) NOT NULL UNIQUE,
  percent integer NOT NULL CHECK (percent BETWEEN 1 AND 90),
  minimum integer NOT NULL CHECK (minimum >= 0),
  max_uses integer NOT NULL CHECK (max_uses > 0),
  used integer NOT NULL DEFAULT 0 CHECK (used BETWEEN 0 AND max_uses),
  active boolean NOT NULL DEFAULT true,
  expires_at timestamptz
);
CREATE TABLE orders (
  id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  folio text NOT NULL UNIQUE,
  user_id text NOT NULL REFERENCES users,
  idempotency_key varchar(100) NOT NULL,
  coupon_id integer REFERENCES coupons,
  status text NOT NULL CHECK (status IN ('simulado','preparando','enviado','entregado','cancelado','reembolsado')),
  subtotal integer NOT NULL CHECK (subtotal >= 0),
  discount integer NOT NULL CHECK (discount BETWEEN 0 AND subtotal),
  shipping integer NOT NULL CHECK (shipping >= 0),
  total integer GENERATED ALWAYS AS (subtotal - discount + shipping) STORED,
  terms_version text NOT NULL,
  terms_accepted_at timestamptz NOT NULL DEFAULT now(),
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(user_id, idempotency_key)
);
CREATE INDEX orders_user_created_idx ON orders(user_id, created_at DESC);
CREATE TABLE order_delivery (
  order_id integer PRIMARY KEY REFERENCES orders,
  recipient text NOT NULL,
  street text NOT NULL,
  neighborhood text NOT NULL,
  city text NOT NULL,
  state text NOT NULL,
  postal_code char(5) NOT NULL CHECK (postal_code ~ '^[0-9]{5}$'),
  phone text NOT NULL,
  shipping_type text NOT NULL CHECK (shipping_type IN ('estandar','express','recoger')),
  tracking text NOT NULL DEFAULT ''
);
CREATE TABLE order_items (
  id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  order_id integer NOT NULL REFERENCES orders,
  variant_id integer NOT NULL REFERENCES product_variants,
  sku varchar(40) NOT NULL,
  name varchar(100) NOT NULL,
  description text NOT NULL,
  size varchar(32) NOT NULL,
  unit_price integer NOT NULL CHECK (unit_price >= 0),
  quantity integer NOT NULL CHECK (quantity BETWEEN 1 AND 10),
  line_total integer GENERATED ALWAYS AS (unit_price * quantity) STORED,
  UNIQUE(order_id, variant_id)
);
CREATE TABLE payments (
  order_id integer PRIMARY KEY REFERENCES orders,
  status text NOT NULL CHECK (status IN ('aprobado','reembolsado')),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE inventory_movements (
  id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  variant_id integer NOT NULL REFERENCES product_variants,
  order_id integer REFERENCES orders,
  actor_id text NOT NULL REFERENCES users,
  delta integer NOT NULL CHECK (delta <> 0),
  reason text NOT NULL CHECK (reason IN ('venta','cancelacion','devolucion','ajuste_admin')),
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(order_id, variant_id, reason)
);
CREATE TABLE return_requests (
  id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  order_id integer NOT NULL REFERENCES orders,
  kind text NOT NULL CHECK (kind IN ('cancelacion','devolucion','garantia')),
  folio text NOT NULL UNIQUE,
  reason text NOT NULL,
  detail text NOT NULL,
  status text NOT NULL DEFAULT 'solicitada' CHECK (status IN ('solicitada','aprobada','rechazada','reembolsada')),
  resolution text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX return_open_order_idx ON return_requests(order_id)
  WHERE status IN ('solicitada', 'aprobada', 'reembolsada');
CREATE TABLE contact_tickets (
  id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  user_id text NOT NULL REFERENCES users,
  folio text NOT NULL UNIQUE,
  name text NOT NULL,
  email text NOT NULL,
  message text NOT NULL,
  status text NOT NULL DEFAULT 'abierto' CHECK (status IN ('abierto','en_revision','resuelto')),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE audit_logs (
  id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  actor_id text NOT NULL REFERENCES users,
  action text NOT NULL,
  entity text NOT NULL,
  entity_id text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
